export function getTranslations(langCode) {
  return T[langCode] || T.en;
}

export function langFromLocale(locale) {
  if (!locale) return 'en';
  const code = locale.split('-')[0].toLowerCase();
  return T[code] ? code : 'en';
}

// Maps English server status labels to the user's language
export function translateStatus(label, t) {
  const map = {
    'Searching the web…':          t.statusSearching,
    'Reading product pages…':      t.statusReading,
    'Ranking results for you…':    t.statusRanking,
    'Thinking about your feedback…': t.statusThinking,
    'Searching for better matches…': t.statusRefining,
  };
  return map[label] || label;
}
